"""Unified Repository coordinator for AurumLens.

Coordinates DuckDB (local high-performance engine), Parquet snapshots,
and optional Supabase cloud persistence.
"""

from datetime import date
import logging
from pathlib import Path
from typing import TYPE_CHECKING, Any, Dict, List, Optional

from aurumlens.db.duckdb_repo import DuckDBRepository
from aurumlens.db.parquet_store import ParquetSnapshotStore
from aurumlens.db.supabase_repo import SupabaseRepository

if TYPE_CHECKING:
    from aurumlens.ingest.quality import QualityAssessedRecord

logger = logging.getLogger(__name__)


class UnifiedRepository:
    """Coordinates local DuckDB analytical store, Parquet snapshots, and Supabase cloud store."""

    def __init__(
        self,
        db_path: Optional[Path] = None,
        processed_dir: Optional[Path] = None,
        enable_supabase: bool = True
    ) -> None:
        self.duckdb_repo = DuckDBRepository(db_path)
        self.parquet_store = ParquetSnapshotStore(processed_dir)
        self.supabase_repo = SupabaseRepository() if enable_supabase else None

    def close(self) -> None:
        """Close resources."""
        self.duckdb_repo.close()

    def persist_ingestion_unit(
        self,
        requested_date: date,
        returned_date: Optional[date],
        adapter: str,
        content: str,
        sha256: str,
        storage_path: str,
        status: str,
        records: List[QualityAssessedRecord],
        dataset_version: str,
        reject_reason: Optional[str] = None
    ) -> int:
        """Persist a single ingested file and its quality-assessed records across all stores.
        
        Returns:
            file_id generated by primary store.
        """
        # 1. Local DuckDB storage
        file_id = self.duckdb_repo.insert_source_file(
            requested_date=requested_date,
            returned_date=returned_date,
            adapter=adapter,
            sha256=sha256,
            storage_path=storage_path,
            status=status,
            reject_reason=reject_reason
        )

        if status == "OK" and records:
            # Upsert contracts
            for r in records:
                self.duckdb_repo.upsert_contract(
                    contract_id=r.contract_id,
                    symbol=r.symbol,
                    expiry_date=r.expiry_date,
                    trade_date=r.trade_date
                )

            # Insert daily prices
            self.duckdb_repo.insert_daily_prices(
                records=records,
                file_id=file_id,
                dataset_version=dataset_version
            )

        # 2. Supabase storage & DB (if enabled and connected)
        if self.supabase_repo and self.supabase_repo.is_connected:
            try:
                # Upload raw file to bucket
                if content:
                    self.supabase_repo.upload_raw_file(storage_path, content)

                # Insert source_file row
                sb_file_id = self.supabase_repo.insert_source_file(
                    requested_date=requested_date,
                    returned_date=returned_date,
                    adapter=adapter,
                    sha256=sha256,
                    storage_path=storage_path,
                    status=status,
                    reject_reason=reject_reason
                )

                if status == "OK" and records:
                    target_file_id = sb_file_id or file_id
                    for r in records:
                        self.supabase_repo.upsert_contract(
                            contract_id=r.contract_id,
                            symbol=r.symbol,
                            expiry_date=r.expiry_date,
                            trade_date=r.trade_date
                        )
                    self.supabase_repo.insert_daily_prices(
                        records=records,
                        file_id=target_file_id,
                        dataset_version=dataset_version
                    )
            except Exception as e:
                logger.warning(f"Non-fatal error syncing to Supabase: {e}")

        return file_id

    def export_snapshot(self, dataset_version: str) -> Dict[str, Any]:
        """Export Parquet snapshot with manifest."""
        return self.parquet_store.export_snapshot(self.duckdb_repo, dataset_version)
